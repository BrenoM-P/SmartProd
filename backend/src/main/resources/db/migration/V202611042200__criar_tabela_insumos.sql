-- RF004: insumos (matéria-prima) com unidade de medida e custo unitário.
-- SQL compatível com PostgreSQL (produção) e H2 (dev/testes).
-- custo_unitario tem 4 casas porque o custo por grama ou por mililitro (ex.: R$ 0,0065) não cabe em 2.
CREATE TABLE insumos (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR(120)  NOT NULL,
    unidade_medida VARCHAR(10)   NOT NULL,
    custo_unitario NUMERIC(12,4) NOT NULL,
    ativo          BOOLEAN       NOT NULL DEFAULT TRUE,
    criado_em      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_insumos_unidade_medida CHECK (unidade_medida IN ('G', 'KG', 'ML', 'L', 'UN')),
    CONSTRAINT ck_insumos_custo_unitario CHECK (custo_unitario >= 0)
);

-- RNF-D002: índice na coluna de consulta frequente (listagem e busca por nome).
CREATE INDEX idx_insumos_nome ON insumos (nome);
